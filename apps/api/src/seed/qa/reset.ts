/**
 * The QA reset: SQL that returns every QA account to "not seeded yet".
 *
 * The nightly run makes real changes on these accounts — resolving exceptions,
 * reviewing check-ins, logging workouts and meals, adding notes (D-QA1-7) — so the
 * reset has to remove everything they own, including rows the run created, and then
 * `qa-seed.sql` puts the known world back.
 *
 * Both QA trainers and both their client worlds are in scope: the predicates are
 * anchored on {@link QA_ACCOUNTS}, so a second trainer is reset by the same
 * statements, with no second code path to keep in step (CU11).
 *
 * Two independent things keep it inside the QA accounts:
 *
 * 1. **Structure.** Every `DELETE` predicate comes from {@link qaScopePredicate},
 *    which is anchored on the literal QA ids (see `ownership.ts`). There is no
 *    unconditional delete, and no predicate mentions any other identity.
 * 2. **A guard.** The statements at the top abort the file (a malformed-JSON error,
 *    so `wrangler d1 execute` exits non-zero) if the database disagrees about which
 *    accounts those ids are: a fixed id that is not its QA account, a QA email or
 *    QA firebase uid on some other user, or a non-QA email on a fixed id.
 *
 * `auth_rate_limits` is intentionally never touched: it is keyed by an IP hash and
 * shared with every other account, so it cannot be scoped to the QA users.
 */
import { QA_ACCOUNTS, qaUserId } from "./accounts.js";
import { sqlQuote } from "../demo/ids.js";
import {
  QA_TABLE_PLAN,
  qaScopePredicate,
  type QaScopeIdentity,
} from "./ownership.js";

function list(values: readonly string[]): string {
  return values.map(sqlQuote).join(", ");
}

/**
 * A statement that succeeds while `okWhenEmpty` matches no row and fails with a
 * SQLite "malformed JSON" error otherwise. SQL has no RAISE outside a trigger;
 * `json()` on a non-JSON string is the portable way to abort a script.
 */
function guard(label: string, from: string, where: string): string {
  return [
    `-- guard: ${label}`,
    `SELECT CASE WHEN count(*) = 0 THEN ${sqlQuote(`qa-reset guard ok: ${label}`)}`,
    `  ELSE json(${sqlQuote(`qa-reset GUARD TRIPPED (${label}) - nothing was deleted`)}) END AS qa_reset_guard`,
    `FROM ${from}`,
    `WHERE ${where};`,
  ].join("\n");
}

export function qaResetGuardSql(): string {
  const ids = QA_ACCOUNTS.map(qaUserId);
  const mismatched = QA_ACCOUNTS.map(
    (account) =>
      `(id = ${sqlQuote(qaUserId(account))} AND firebase_uid <> ${sqlQuote(account.firebaseUid)})`,
  ).join("\n     OR ");
  return [
    guard(
      "each fixed QA id is its QA account",
      "users",
      `${mismatched}`,
    ),
    guard(
      "no QA email or QA firebase uid outside the fixed ids",
      "users u LEFT JOIN user_identities i ON i.user_id = u.id",
      `u.id NOT IN (${list(ids)})\n  AND (u.firebase_uid IN (${list(QA_ACCOUNTS.map((a) => a.firebaseUid))})\n       OR i.email_norm IN (${list(QA_ACCOUNTS.map((a) => a.email))}))`,
    ),
    guard(
      "no non-QA email on a fixed QA id",
      "user_identities",
      `user_id IN (${list(ids)})\n  AND email_norm NOT IN (${list(QA_ACCOUNTS.map((a) => a.email))})`,
    ),
  ].join("\n\n");
}

/**
 * Deletes every row the QA accounts own, in reverse ownership-plan order so
 * each table's parents are still there when its own rows go.
 */
export function buildQaResetSql(identity: QaScopeIdentity): string {
  const parts: string[] = [
    "-- FitBud QA reset (QT2). Generated by apps/api/scripts/qa-reset.ts; do not edit by hand.",
    `-- Scoped to exactly ${identity.userIds.length} QA user ids: ${identity.userIds.join(", ")}`,
    "-- Apply before qa-seed.sql. Never run against production.",
    "PRAGMA defer_foreign_keys = true;",
    "",
    qaResetGuardSql(),
    "",
  ];
  for (const plan of [...QA_TABLE_PLAN].reverse()) {
    const predicate = qaScopePredicate(plan.table, identity, "reset");
    parts.push(`DELETE FROM ${plan.table} WHERE ${predicate};`);
  }
  return `${parts.join("\n")}\n`;
}
