const path = require("path");
const fs = require("fs");
const { withAndroidManifest, withDangerousMod } = require("expo/config-plugins");

/** Info.plist key the host app publishes its App Group under. */
const APP_GROUP_INFO_PLIST_KEY = "FitBudAppGroup";

/**
 * Where the widget's App Group constant is generated, relative to the Expo
 * project root. The file sits inside targets/FitBudLiveActivity, which
 * @bacons/apple-targets adds to the widget target as an Xcode synchronized
 * folder, so every .swift file in it is compiled into the widget with no
 * project edit and no ordering dependency on the apple-targets mods.
 */
const APP_GROUP_SWIFT_PATH = path.join(
  "targets",
  "FitBudLiveActivity",
  "GeneratedAppGroup.swift",
);

/** Swift type and member the widget reads the group name from. */
const APP_GROUP_SWIFT_TYPE = "FitBudAppGroup";
const APP_GROUP_SWIFT_MEMBER = "identifier";

/** A group name must be a plain identifier before it goes in a Swift literal. */
const APP_GROUP_PATTERN = /^group\.[A-Za-z0-9][A-Za-z0-9.-]*$/;

/** @param {string} appGroup */
function appGroupSwiftSource(appGroup) {
  if (!APP_GROUP_PATTERN.test(appGroup)) {
    throw new Error(
      `withLiveActivity: "${appGroup}" is not a usable App Group name.`,
    );
  }
  return `// Generated by apps/mobile/plugins/withLiveActivity.js on expo prebuild.
// Do not edit and do not commit: the name differs per app variant (APP_VARIANT
// in app.config.js), so prebuild rewrites this file for every build.
//
// The group name is compiled in rather than read from the widget's Info.plist:
// @bacons/apple-targets 0.2.1 never writes a target's \`infoPlist\` into the
// widget bundle, so Bundle.main.object(forInfoDictionaryKey:) returns nil there
// and every lock-screen write would land in the widget's own defaults.
enum ${APP_GROUP_SWIFT_TYPE} {
  /// App Group shared with the host app, which holds the same entitlement.
  static let ${APP_GROUP_SWIFT_MEMBER} = "${appGroup}"
}
`;
}

/**
 * Writes that constant on prebuild. iOS only: an Android-only prebuild never
 * runs an "ios" dangerous mod.
 *
 * @param {import('@expo/config').ExpoConfig} config
 * @param {string} appGroup
 */
function withAppGroupConstant(config, appGroup) {
  const source = appGroupSwiftSource(appGroup);
  return withDangerousMod(config, [
    "ios",
    (modConfig) => {
      const file = path.join(
        modConfig.modRequest.projectRoot,
        APP_GROUP_SWIFT_PATH,
      );
      const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
      if (current !== source) {
        fs.mkdirSync(path.dirname(file), { recursive: true });
        fs.writeFileSync(file, source);
      }
      return modConfig;
    },
  ]);
}

/**
 * The receiver behind the Android workout notification's buttons (LA3).
 * Fully qualified and fixed: the app's package changes per variant
 * (app.config.js), the local Expo module's does not.
 */
const WORKOUT_RECEIVER = "com.thefitbud.liveactivity.WorkoutSetActionReceiver";

/**
 * Registers that receiver in the app's manifest. Not exported and with no
 * intent filter: only FitBud's own explicit PendingIntents reach it, so no
 * other app can press −, + or Log set. `directBootAware` is left off; the
 * notification is posted after the user has unlocked at least once.
 *
 * @param {import('@expo/config').ExpoConfig} config
 */
function withWorkoutSetReceiver(config) {
  return withAndroidManifest(config, (mod) => {
    const application = mod.modResults.manifest.application?.[0];
    if (!application) {
      throw new Error(
        "withLiveActivity: the Android manifest has no <application> element.",
      );
    }
    const receivers = application.receiver ?? [];
    const existing = receivers.find(
      (receiver) => receiver.$?.["android:name"] === WORKOUT_RECEIVER,
    );
    const attributes = {
      "android:name": WORKOUT_RECEIVER,
      "android:exported": "false",
      "android:enabled": "true",
    };
    if (existing) {
      existing.$ = { ...existing.$, ...attributes };
    } else {
      receivers.push({ $: attributes });
    }
    application.receiver = receivers;
    return mod;
  });
}

/**
 * Marks the iOS app as Live Activity capable and shares an App Group
 * with targets/FitBudLiveActivity. The group differs per app variant
 * (app.config.js). The host app gets it as the FitBudAppGroup Info.plist key
 * and as an entitlement; the widget gets it as a generated Swift constant
 * (withAppGroupConstant), because a widget target's Info.plist keys never
 * reach its bundle with @bacons/apple-targets 0.2.1.
 *
 * The widget target and LiveActivityIntent buttons are not compiled by
 * Expo web or Expo Go. They need a dev build: @bacons/apple-targets (in the
 * plugins list, LA1) adds targets/FitBudLiveActivity to the iOS build.
 * Log set advances to the next set. After a set logged in the app, the
 * activity shows the rest countdown (frame 27c, LA1c) until it runs out or
 * Skip is tapped.
 * The Android custom notification lives in targets/android, compiled by the
 * local Expo module in modules/live-activity/android (LA3), and also needs
 * that dev build. It is not part of the Expo web bundle. This plugin
 * registers its button receiver in the Android manifest.
 *
 * @param {import('@expo/config').ExpoConfig} config
 * @param {{ appGroup: string }} options
 */
function withLiveActivity(config, options) {
  const appGroup = options?.appGroup;
  if (!appGroup) {
    throw new Error("withLiveActivity needs an appGroup option.");
  }
  const ios = config.ios ?? {};
  const groups = new Set(
    ios.entitlements?.["com.apple.security.application-groups"] ?? [],
  );
  groups.add(appGroup);
  const withIos = {
    ...config,
    ios: {
      ...ios,
      infoPlist: {
        ...(ios.infoPlist ?? {}),
        NSSupportsLiveActivities: true,
        [APP_GROUP_INFO_PLIST_KEY]: appGroup,
      },
      entitlements: {
        ...(ios.entitlements ?? {}),
        "com.apple.security.application-groups": [...groups],
      },
    },
  };
  return withWorkoutSetReceiver(withAppGroupConstant(withIos, appGroup));
}

module.exports = withLiveActivity;
module.exports.APP_GROUP_INFO_PLIST_KEY = APP_GROUP_INFO_PLIST_KEY;
module.exports.WORKOUT_RECEIVER = WORKOUT_RECEIVER;
module.exports.APP_GROUP_SWIFT_PATH = APP_GROUP_SWIFT_PATH;
module.exports.appGroupSwiftSource = appGroupSwiftSource;
