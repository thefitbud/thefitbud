// Bundles the published markdown into documents.ts, which the trainer web and
// mobile apps import (Metro cannot import .md). Run after editing any .md file:
//   node docs/legal/published/build-documents.mjs
// A trainer-web test fails if documents.ts is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const slugs = [
  "terms",
  "trainer-terms",
  "trainee-terms",
  "privacy",
  "health",
  "acceptable-use",
  "beta",
  "credits",
];

let out =
  "// Generated by build-documents.mjs from the .md files in this folder. Do not edit.\n" +
  'import type { LegalSlug } from "./registry";\n\n' +
  "export const LEGAL_MARKDOWN: Record<LegalSlug, string> = {\n";
for (const slug of slugs) {
  const text = readFileSync(join(dir, `${slug}.md`), "utf8");
  out += `  ${JSON.stringify(slug)}: ${JSON.stringify(text)},\n`;
}
out += "};\n";
writeFileSync(join(dir, "documents.ts"), out);
